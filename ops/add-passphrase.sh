#!/bin/sh
# ใส่ "รหัสที่เปิดก้อน" ลงในรีโปนี้ — ★ ผู้ใช้เป็นคนพิมพ์เอง ไม่มีใครรับไปพิมพ์แทน
#
#   sh ops/add-passphrase.sh
#
# ★★★ อ่านก่อนรัน — รันแล้วเปลี่ยนความหมายของรีโปนี้ทั้งรีโป
#   รหัสกับก้อนจะอยู่ที่เดียวกัน ใครได้รีโปไปคือได้ทั้งก้อนและกุญแจพร้อมกัน
#   ➜ **ตั้งแต่วินาทีนั้นให้ถือว่าก้อนนี้เป็นข้อความเปล่า** ไม่ใช่ของที่เข้ารหัสแล้ว
#   ➜ ถ้าวันหนึ่งรีโปหลุดหรือถูกแชร์ผิดคน ต้อง **เปลี่ยนค่าทุกตัวในก้อน** ตามตาราง
#     ข้อ 2 ของ รายการความลับ.md ไม่ใช่แค่ลบไฟล์นี้ทิ้ง (git เก็บประวัติไว้ถาวร)
set -eu
cd "$(dirname "$0")/.."
. ops/lib.sh

OUT="รหัสเปิดก้อน.txt"
bundle=$(newest_bundle || true)
[ -n "$bundle" ] || { echo "ยังไม่มีก้อนในรีโปนี้ — ทำก้อนก่อนด้วย ops/ship.sh"; exit 1; }

echo "ก้อนที่รหัสนี้ใช้เปิด: $(basename "$bundle")"
echo
echo "★★ รันแล้วรหัสกับก้อนจะอยู่ที่เดียวกัน = เท่ากับไม่ได้เข้ารหัส"
echo "   ใครเปิดรีโปนี้ได้ อ่านค่าจริงได้ทั้งหมด"
printf 'เข้าใจแล้วและยืนยัน (พิมพ์ ใช่ เท่านั้น) ? '
read -r sure
[ "$sure" = "ใช่" ] || { echo "ยกเลิก — ไม่ได้แก้อะไรเลย"; exit 1; }

# ── รับรหัสโดยไม่แสดงบนจอ และไม่ผ่านประวัติคำสั่ง ─────────────────────────
# ★ ปิดการแสดงผลเฉพาะตอนที่ stdin เป็นหน้าจอจริง — ไม่งั้น stty จะล้ม
#   ("stdin isn't a terminal") และสคริปต์จะใช้ไม่ได้เลยตอนทดสอบด้วยท่อ
if [ -t 0 ]; then old_stty=$(stty -g); trap 'stty "$old_stty" 2>/dev/null' EXIT INT TERM HUP; fi
hide() { [ -t 0 ] && stty -echo; return 0; }
show() { [ -t 0 ] && stty "$old_stty"; return 0; }

# ★ ต้องมี IFS= นำหน้า read ไม่งั้นช่องว่างหัว/ท้ายของรหัสถูกตัดทิ้งเงียบ ๆ
#   แล้วรหัสที่ถูกจะกลายเป็นรหัสผิดโดยไม่มีอะไรบอก
printf '\nพิมพ์รหัสที่เปิดก้อน (ไม่แสดงบนจอ): '
hide; IFS= read -r pass1; show; echo
printf 'พิมพ์อีกครั้งให้ตรงกัน: '
hide; IFS= read -r pass2; show; echo
[ -n "$pass1" ] || { echo "ว่างเปล่า — ยกเลิก"; exit 1; }
[ "$pass1" = "$pass2" ] || { echo "สองครั้งไม่ตรงกัน — ยกเลิก ไม่ได้เขียนอะไร"; exit 1; }

# ── ★ ตรวจว่ารหัสนี้เปิดก้อนได้จริง ก่อนจะเขียนลงไฟล์ ────────────────────
#   รหัสผิดที่ถูกเก็บไว้ในรีโปแย่กว่าไม่มีรหัสเลย เพราะคนรับช่วงจะเชื่อว่ามันถูก
echo "— ลองเปิดก้อนด้วยรหัสนี้ —"
n=$(printf '%s\n' "$pass1" \
  | openssl enc -d -aes-256-cbc -pbkdf2 -iter 600000 -in "$bundle" -pass stdin 2>/dev/null \
  | LC_ALL=en_US.UTF-8 tar tzf - 2>/dev/null | grep -vcE '^(\./)?$' || true)
if [ "${n:-0}" -lt 6 ]; then
  echo "[ เปิดไม่ได้ ] รหัสนี้เปิดก้อนไม่ออก (ได้ ${n:-0} ไฟล์ ควรได้ 6) — ไม่เขียนอะไรทั้งนั้น"
  exit 1
fi
echo "เปิดได้ $n ไฟล์ — รหัสถูกต้อง"

# ★★ บรรทัดแรกต้องเป็นตัวรหัสล้วน ๆ เพราะ `openssl -pass file:` อ่านแค่บรรทัดแรก
#   ถ้าเอาคำอธิบายขึ้นก่อน สคริปต์อื่นจะเอาคำอธิบายไปใช้เป็นรหัสแล้วเปิดไม่ออก
{
  echo "$pass1"
  echo
  echo "— รหัสข้างบนใช้เปิด $(basename "$bundle") —"
  echo "★★ ไฟล์นี้ทำให้ก้อนข้างบนไม่ต่างจากข้อความเปล่า — ใครเปิดรีโปนี้ได้ อ่านค่าจริงได้หมด"
  echo "★★ รีโปหลุดเมื่อไร ต้องเปลี่ยนค่าทุกตัวในก้อน ไม่ใช่แค่ลบไฟล์นี้ (git เก็บประวัติถาวร)"
} > "$OUT"
chmod 600 "$OUT"
unset pass1 pass2

git config core.hooksPath .githooks
git add "$OUT"
git -c core.quotePath=false commit -q -m "ใส่รหัสที่เปิดก้อนลงในรีโปนี้ (ผู้ใช้สั่ง)

★★ ตั้งแต่คอมมิตนี้ รหัสกับก้อนอยู่ที่เดียวกัน — ถือว่าก้อนเป็นข้อความเปล่า
ใครเปิดรีโปนี้ได้ อ่านค่าจริงได้ทั้งหมด · รีโปหลุดเมื่อไรต้องเปลี่ยนค่าทุกตัว
ไม่ใช่แค่ลบไฟล์ทิ้ง เพราะ git เก็บประวัติไว้ถาวร"
git push -q origin HEAD
echo
echo "[ เสร็จ ] $(git log --oneline -1)"
echo "➜ ตอนนี้ลิงก์รีโปนี้ = ค่าจริงทั้งหมด ส่งลิงก์ให้ใครเท่ากับส่งรหัสทุกตัวให้คนนั้น"
