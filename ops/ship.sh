#!/bin/sh
# ★ คำสั่งเดียวจบ — ทำใบใหม่ · ตรวจว่าเปิดได้จริง · commit · push
#
#   BOX=root@<ที่อยู่ของกล่อง> sh ops/ship.sh
#
# จะถามรหัสผ่าน 3 ครั้ง — สองครั้งแรกคือตอนปิดผนึก (ยืนยันกันพิมพ์ผิด)
# ครั้งที่สามคือตอนเปิดดูว่าเปิดได้จริง ★ ขั้นนี้ข้ามไม่ได้
# "สำรองที่ไม่เคยลองเปิด = ยังไม่รู้ว่าสำรองได้หรือเปล่า"
set -eu
cd "$(dirname "$0")/.."
. ops/lib.sh
box_required

# ให้ตัวกันความลับหลุดทำงานแน่ ๆ (git ไม่ติดตั้ง hook ให้เองตอน clone)
git config core.hooksPath .githooks

echo "═══ 1/4 ตรวจต้นทาง ═══"
sh ops/preflight.sh

echo
echo "═══ 2/4 ปิดผนึกใบใหม่ (ถามรหัส 2 ครั้ง) ═══"
sh ops/seal.sh
new=$(newest_bundle)

echo
echo "═══ 3/4 เปิดดูว่าเปิดได้จริง (ถามรหัสอีกครั้ง) ═══"
sh ops/verify.sh --expect 6 "$new"

printf '\nเปิดได้ครบ 6 ไฟล์ตามด้านบนแล้ว · ยืนยัน push ไหม (y = push · อย่างอื่น = หยุด) ? '
read -r ans
case "$ans" in
  y|Y|yes) ;;
  *) echo "หยุดแล้ว — ใบอยู่ที่ $new แต่ยังไม่ขึ้น git"; exit 1 ;;
esac

echo
echo "═══ 4/4 ขึ้น git ═══"
git add "$new"
git -c core.quotePath=false commit -q -m "ใส่ค่าจริงครบทุกตัว — ก้อน $(basename "$new")

ค่าจริงทั้ง 6 ไฟล์อยู่ในก้อนที่เข้ารหัส AES-256 (pbkdf2 600,000 รอบ) ก้อนนี้
เปิดดูแล้วว่าเปิดได้จริงก่อน commit ★ รหัสที่เปิดก้อนไม่ได้อยู่ในรีโปนี้
และต้องไม่ส่งทางเดียวกับลิงก์รีโป"
git push -q origin HEAD
echo "push แล้ว — $(git log --oneline -1)"

cat <<'TXT'

═══════════════════════════════════════════════════════════
★★ เหลือสองอย่างที่โปรแกรมทำแทนไม่ได้

1. ส่งรหัสที่เปิดก้อน — ⚠ ตัวต่อตัว · คนละช่องทางกับลิงก์รีโป
   เก็บในโปรแกรมจัดการรหัสผ่านของบริษัท หรือใส่ซองปิดผนึก
   **ห้ามลงกลุ่มรวม และห้ามส่งทางเดียวกับที่ส่งลิงก์รีโปนี้**

2. ให้สิทธิ์รีโปนี้กับคนของบริษัท **อย่างน้อยสองคน**
   ไม่งั้นก็แค่ย้าย "มีคนเดียวที่เปิดได้" ไปไว้ที่คนใหม่

★ ทำเสร็จสองข้อนี้แล้ว ข้อที่ขวางการส่งมอบข้อแรกถือว่าปิดได้
═══════════════════════════════════════════════════════════
TXT
