#!/bin/sh
# ★ คำสั่งเดียวจบ — ทำใบใหม่ · ตรวจว่าเปิดได้จริง · commit · push
#
#   BOX=root@<ที่อยู่ของกล่อง> sh ops/ship.sh
#
# จะถามรหัสผ่าน 3 ครั้ง — สองครั้งแรกคือตอนปิดผนึก (ยืนยันกันพิมพ์ผิด)
# ครั้งที่สามคือตอนเปิดดูว่าเปิดได้จริง ★ ขั้นนี้ข้ามไม่ได้
# "สำรองที่ไม่เคยลองเปิด = ยังไม่รู้ว่าสำรองได้หรือเปล่า"
set -eu
cd "$(dirname "$0")/.."
. ops/lib.sh
box_required

# ── --auto-key : ไม่ต้องพิมพ์รหัสและไม่ต้องจำ ────────────────────────────
#   สุ่มรหัสเก็บเป็นไฟล์ในรีโปนี้เลย แล้วใช้ไฟล์นั้นปิดผนึกและเปิดตรวจ
#   ★★ ใช้ได้เพราะผู้ใช้สั่งให้รหัสอยู่ในรีโปเดียวกับก้อนอยู่แล้ว (13 พ.ย. 2569)
#      การพิมพ์รหัสเองจึงไม่ได้เพิ่มความปลอดภัยอะไร มีแต่ความเสี่ยงว่าจะจำไม่ได้
#      — ซึ่งเกิดมาแล้วกับก้อน 6 พ.ย. ที่เปิดไม่ออก
auto_key=0
[ "${1:-}" = "--auto-key" ] && auto_key=1


# ให้ตัวกันความลับหลุดทำงานแน่ ๆ (git ไม่ติดตั้ง hook ให้เองตอน clone)
git config core.hooksPath .githooks

echo "═══ 1/4 ตรวจต้นทาง ═══"
sh ops/preflight.sh

# ★ สุ่มรหัสหลังตรวจต้นทางผ่านแล้วเท่านั้น — ของเดิมสุ่มก่อน พอ preflight ล้ม
#   ก็เหลือไฟล์รหัสค้างอยู่ทั้งที่ไม่มีก้อนไหนใช้มัน (เจอจริง 13 พ.ย. 2569)
if [ "$auto_key" = 1 ]; then
  if [ ! -f "$KEYFILE" ]; then
    echo "— สุ่มรหัสใหม่เก็บไว้ที่ $KEYFILE —"
    {
      openssl rand -base64 48 | tr -d '\n'
      echo
      echo
      echo "— รหัสบรรทัดแรกใช้เปิดก้อนใน ก้อนความลับ/ —"
      echo "★★ ไฟล์นี้ทำให้ก้อนไม่ต่างจากข้อความเปล่า ใครเปิดรีโปนี้ได้ อ่านค่าจริงได้หมด"
      echo "★★ รีโปหลุดเมื่อไร ต้องเปลี่ยนค่าทุกตัวในก้อน ไม่ใช่แค่ลบไฟล์นี้ (git เก็บประวัติถาวร)"
    } > "$KEYFILE"
    chmod 600 "$KEYFILE"
  else
    echo "— ใช้รหัสเดิมที่มีอยู่แล้วใน $KEYFILE —"
  fi
  PASSFILE="$PWD/$KEYFILE"
  export PASSFILE
fi

echo
if [ "$auto_key" = 1 ]; then
  echo "═══ 2/4 ปิดผนึกใบใหม่ (ใช้รหัสจากไฟล์ ไม่ต้องพิมพ์) ═══"
else
  echo "═══ 2/4 ปิดผนึกใบใหม่ (ถามรหัส 2 ครั้ง) ═══"
fi
sh ops/seal.sh
new=$(newest_bundle)

echo
echo "═══ 3/4 เปิดดูว่าเปิดได้จริง ═══"
sh ops/verify.sh --expect 6 "$new"

printf '\nเปิดได้ครบ 6 ไฟล์ตามด้านบนแล้ว · ยืนยัน push ไหม (y = push · อย่างอื่น = หยุด) ? '
# ★ อ่านจาก /dev/tty ไม่ใช่ stdin — โปรเซสลูก (preflight/seal/verify) กิน stdin ไปก่อนได้
#   เจอจริง 13 พ.ย. 2569: ป้อน y ทางท่อแล้วสคริปต์หยุดที่ช่องนี้เฉย ๆ ไม่ push
if [ -r /dev/tty ]; then IFS= read -r ans < /dev/tty; else IFS= read -r ans; fi
case "$ans" in
  y|Y|yes) ;;
  *) echo "หยุดแล้ว — ใบอยู่ที่ $new แต่ยังไม่ขึ้น git"; exit 1 ;;
esac

echo
echo "═══ 4/4 ขึ้น git ═══"
git add "$new"
[ "$auto_key" = 1 ] && git add "$KEYFILE"
git -c core.quotePath=false commit -q -m "ใส่ค่าจริงครบทุกตัว — ก้อน $(basename "$new")

ค่าจริงทั้ง 6 ไฟล์อยู่ในก้อนที่เข้ารหัส AES-256 (pbkdf2 600,000 รอบ) ก้อนนี้
เปิดดูแล้วว่าเปิดได้จริงก่อน commit ★ รหัสที่เปิดก้อนไม่ได้อยู่ในรีโปนี้
และต้องไม่ส่งทางเดียวกับลิงก์รีโป"
git push -q origin HEAD
echo "push แล้ว — $(git log --oneline -1)"

if [ "$auto_key" = 1 ]; then
cat <<'TXT'

═══════════════════════════════════════════════════════════
★★ รหัสอยู่ในรีโปนี้แล้ว (ไฟล์ รหัสเปิดก้อน.txt) ไม่ต้องส่งแยกและไม่ต้องจำ

➜ **ลิงก์รีโปนี้ = ค่าจริงทั้งหมด** ใครเปิดรีโปได้ อ่านรหัสทุกตัวได้
   ส่งลิงก์ให้ใครเท่ากับส่งรหัสทุกตัวให้คนนั้น — เลือกคนที่ให้สิทธิ์ให้ดี

เหลืออย่างเดียว: **ให้สิทธิ์รีโปนี้กับคนของบริษัทอย่างน้อยสองคน**
ไม่งั้นก็แค่ย้าย "มีคนเดียวที่เปิดได้" ไปไว้ที่คนใหม่

⚠ ถ้าวันหนึ่งรีโปหลุดหรือถูกแชร์ผิดคน ต้อง **เปลี่ยนค่าทุกตัวในก้อน**
   ไม่ใช่แค่ลบไฟล์รหัสทิ้ง เพราะ git เก็บประวัติไว้ถาวร
═══════════════════════════════════════════════════════════
TXT
else
cat <<'TXT'

═══════════════════════════════════════════════════════════
★★ เหลือสองอย่างที่โปรแกรมทำแทนไม่ได้

1. ส่งรหัสที่เปิดก้อน — ⚠ ตัวต่อตัว · คนละช่องทางกับลิงก์รีโป
   เก็บในโปรแกรมจัดการรหัสผ่านของบริษัท หรือใส่ซองปิดผนึก
   **ห้ามลงกลุ่มรวม และห้ามส่งทางเดียวกับที่ส่งลิงก์รีโปนี้**

2. ให้สิทธิ์รีโปนี้กับคนของบริษัท **อย่างน้อยสองคน**
   ไม่งั้นก็แค่ย้าย "มีคนเดียวที่เปิดได้" ไปไว้ที่คนใหม่

★ ทำเสร็จสองข้อนี้แล้ว ข้อที่ขวางการส่งมอบข้อแรกถือว่าปิดได้
═══════════════════════════════════════════════════════════
TXT
fi
