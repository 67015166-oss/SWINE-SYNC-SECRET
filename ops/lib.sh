# ค่าร่วมของสคริปต์ในโฟลเดอร์นี้ — ไม่ได้รันตรง ๆ
# ★ ไม่มีที่อยู่เครื่องและไม่มีค่าความลับฝังในไฟล์นี้ ต้องส่งเข้ามาตอนเรียกเสมอ

REPO=$(cd "$(dirname "$0")/.." && pwd)
BUNDLES="${BUNDLES:-$REPO/ก้อนความลับ}"

APP="${APP:-$HOME/cpf_dashboard}"   # รีโปโค้ด — ตั้ง APP= ทับได้
NR="${NR:-$HOME/.node-red}"         # โฟลเดอร์ของตัวรับค่าเซนเซอร์

# ★ ทดสอบสคริปต์พวกนี้ได้โดยไม่ต้องแตะกล่องจริง — ตั้ง SRC_ENV กับ SRC_PW
#   ให้ชี้ไฟล์ปลอมในเครื่อง แล้วทุกสคริปต์จะเลิกถาม/เลิก ssh หากล่อง
src_overridden() { [ -n "${SRC_ENV:-}" ] && [ -n "${SRC_PW:-}" ]; }

# ที่อยู่กล่อง — ★ ไม่มีค่าตั้งต้นโดยเจตนา เพื่อไม่ให้ที่อยู่เครื่องขึ้น git
box_required() {
  src_overridden && return 0
  if [ -z "${BOX:-}" ]; then
    echo "ตั้งที่อยู่กล่องก่อน เช่น" >&2
    echo "    BOX=root@<ที่อยู่ของกล่อง> sh $0" >&2
    exit 2
  fi
}

BOX_ENV="${BOX_ENV:-/home/dev/swine/app/.env}"
BOX_PW="${BOX_PW:-/home/dev/รหัสผ่านของระบบ.txt}"

# ปีพุทธศักราชของวันนี้
be_today() { echo "$(( $(date +%Y) + 543 ))-$(date +%m-%d)"; }

# ใบล่าสุดในโฟลเดอร์ (เรียงตามชื่อ ซึ่งมีวันที่อยู่ในตัว)
newest_bundle() { ls -1 "$BUNDLES"/*.tar.gz.enc 2>/dev/null | sort | tail -1; }
